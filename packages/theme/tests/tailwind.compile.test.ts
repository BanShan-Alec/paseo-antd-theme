import { readFileSync } from "node:fs";
import { join } from "node:path";
import { beforeAll, describe, expect, it } from "vitest";
import { compile } from "@tailwindcss/node";
import { TAILWIND_VARIABLES } from "../src/tailwind/build";

const ROOT = join(import.meta.dirname, "..");

/**
 * The structural tests in tailwind.test.ts prove the stylesheet is
 * well-formed; only the real Tailwind v4 compiler can prove it is *usable* —
 * that every `--color-*` key actually resolves to utilities, that `@theme
 * inline` passes values through, and that both dark strategies compile.
 * This file is that gate: it walks every exported color key and asserts the
 * corresponding `bg-` / `text-` utilities are generated by tailwindcss
 * itself. A Tailwind release that changes name resolution fails here.
 */

/** `text-*` maps to `--color-*` — but keys starting with `text-` would need `text-text-*`. */
function colorUtilityClass(prefix: "bg" | "text", key: string): string {
  if (prefix === "text" && key.startsWith("text-")) {
    return `text-text-${key.slice("text-".length)}`;
  }
  return `${prefix}-${key}`;
}

let css = "";

beforeAll(async () => {
  const stylesheet = readFileSync(join(ROOT, "src/tailwind/theme.css"), "utf8");
  const compiler = await compile(`@import "tailwindcss";\n@import "./src/tailwind/theme.css";`, {
    base: ROOT,
    onDependency: () => {},
  });
  const candidates: string[] = ["font-sans", "font-mono", "rounded-xs", "rounded-sm", "rounded-md", "rounded-lg"];
  for (const spec of TAILWIND_VARIABLES) {
    if (spec.kind !== "color") continue;
    candidates.push(`bg-${spec.name}`);
    candidates.push(colorUtilityClass("text", spec.name));
  }
  // Class-strategy dark variant: the stylesheet supports both, but Tailwind's
  // default is the media strategy, so the class variant needs the same
  // @custom-variant line consumers must add.
  const classCompiler = await compile(
    `@import "tailwindcss";\n@import "./src/tailwind/theme.css";\n@custom-variant dark (&:where(.dark, .dark *));`,
    { base: ROOT, onDependency: () => {} },
  );
  const mediaOut = compiler.build([...candidates, "dark:bg-primary"]);
  const classOut = classCompiler.build(["dark:bg-primary"]);
  css = mediaOut + "\n" + classOut;
});

function escape(cls: string): string {
  return cls.replaceAll(":", "\\:").replaceAll("/", "\\/");
}

describe("tailwind v4 compiles the stylesheet into working utilities", () => {
  it("generates a utility for every exported color key's bg- and text- classes", () => {
    const colorKeys = TAILWIND_VARIABLES.filter((s) => s.kind === "color").map((s) => s.name);
    expect(colorKeys.length).toBeGreaterThan(90);
    for (const key of colorKeys) {
      for (const cls of [`bg-${key}`, colorUtilityClass("text", key)]) {
        expect(css, `utility .${escape(cls)} was not generated`).toContain(`.${escape(cls)} {`);
      }
    }
  });

  it("passes theme values through @theme inline to the utilities", () => {
    // inline means the utility references the underlying --paseo-* variable,
    // not an intermediate --color-* definition.
    expect(css).toContain(".bg-primary {\n    background-color: var(--paseo-primary);\n  }");
  });

  it("compiles dark:bg-primary under the default media strategy", () => {
    expect(css).toContain("@media (prefers-color-scheme: dark) {");
  });

  it("compiles dark:bg-primary under the class strategy with @custom-variant", () => {
    expect(css).toContain(".dark\\:bg-primary:where(.dark, .dark *) {");
  });

  it("generates the font and radius scale utilities", () => {
    for (const cls of ["font-sans", "font-mono", "rounded-xs", "rounded-sm", "rounded-md", "rounded-lg"]) {
      expect(css).toContain(`.${cls} {`);
    }
  });
});
